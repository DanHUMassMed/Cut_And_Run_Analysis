"""Nextflow pipeline execution service and subprocess runner abstraction."""

from __future__ import annotations

import asyncio
import logging
import os
import signal
import time
from pathlib import Path
from typing import Any, Protocol

from repositories import ConfigRepository
from services.task_tracker import ANSI_ESCAPE_RE, LogBroadcaster, TaskTracker
from settings import WorkspaceSettings

logger = logging.getLogger(__name__)


class SubprocessHandle(Protocol):
    """Minimal async subprocess interface required by PipelineService."""

    @property
    def pid(self) -> int: ...
    @property
    def stdout(self) -> asyncio.StreamReader | None: ...
    @property
    def stderr(self) -> asyncio.StreamReader | None: ...
    async def wait(self) -> int: ...


class PipelineRunner(Protocol):
    """Abstraction for launching and signaling pipeline subprocesses."""

    async def spawn(self, cmd: list[str], cwd: Path) -> SubprocessHandle: ...
    def interrupt(self, process: SubprocessHandle) -> None: ...


class NextflowSubprocessRunner:
    """Default asyncio subprocess runner with isolated process group."""

    async def spawn(self, cmd: list[str], cwd: Path) -> SubprocessHandle:
        return await asyncio.create_subprocess_exec(
            *cmd,
            cwd=str(cwd),
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            start_new_session=True,
        )

    def interrupt(self, process: SubprocessHandle) -> None:
        os.killpg(os.getpgid(process.pid), signal.SIGINT)


class PipelineService:
    """Coordinates Nextflow execution, webhook handling, trace reconciliation, and SSE logs."""

    def __init__(
        self,
        settings: WorkspaceSettings,
        config_repo: ConfigRepository,
        tracker: TaskTracker,
        broadcaster: LogBroadcaster,
        runner: PipelineRunner,
    ) -> None:
        self._settings = settings
        self._config_repo = config_repo
        self.tracker = tracker
        self.broadcaster = broadcaster
        self._runner = runner
        self.process: SubprocessHandle | None = None
        self.stream_task: asyncio.Task[None] | None = None

    def ensure_weblog_config(self, port: int = 8000) -> Path:
        weblog_cfg = self._settings.weblog_config_path
        weblog_cfg.parent.mkdir(parents=True, exist_ok=True)
        content = f"""// Auto-generated by CUT&RUN Control Center for real-time progress monitoring
plugins {{
    id 'nf-weblog'
}}
weblog {{
    enabled = true
    url = 'http://127.0.0.1:{port}/api/pipeline/webhook'
}}
"""
        weblog_cfg.write_text(content, encoding="utf-8")
        return weblog_cfg

    def build_command(self, resume: bool, weblog_cfg: Path) -> list[str]:
        return [
            "bash",
            str(self._settings.run_sh_path),
            "true" if resume else "false",
            "-ansi-log",
            "false",
            "-c",
            str(weblog_cfg),
        ]

    async def start(self, resume: bool, request_port: int | None = None) -> dict[str, Any]:
        if self.tracker.status == "running" and self.process is not None:
            raise RuntimeError("Pipeline is already running")

        self.tracker.reset_for_run(time.time())
        self.broadcaster.clear_history()

        effective_port = self._settings.port or request_port or 8000
        weblog_cfg = self.ensure_weblog_config(effective_port)
        cmd = self.build_command(resume=resume, weblog_cfg=weblog_cfg)

        try:
            proc = await self._runner.spawn(cmd, cwd=self._settings.workspace_dir)
            self.process = proc
            self.tracker.status = "running"
            self.stream_task = asyncio.create_task(self.stream_subprocess_output(proc))
            return {
                "status": "started",
                "pid": proc.pid,
                "start_time": self.tracker.start_time,
            }
        except Exception:
            self.tracker.status = "failed"
            if self.tracker.end_time is None:
                self.tracker.end_time = time.time()
            raise

    async def stop(self) -> dict[str, Any]:
        if self.process is None or self.tracker.status != "running":
            return {"status": "not_running"}

        try:
            self._runner.interrupt(self.process)
            self.tracker.cancel_requested = True
            self.tracker.status = "cancelled"
            if self.tracker.end_time is None:
                self.tracker.end_time = time.time()
            self.tracker.compute_stats()
            return {"status": "stopping"}
        except ProcessLookupError:
            return {"status": "process_already_exited"}

    async def stream_subprocess_output(self, proc: SubprocessHandle) -> None:
        self.tracker.status = "running"
        self.tracker.return_code = None

        async def _read_stream(stream: asyncio.StreamReader) -> None:
            while True:
                line = await stream.readline()
                if not line:
                    break
                text = line.decode("utf-8", errors="replace")
                clean_text = ANSI_ESCAPE_RE.sub("", text)
                self.broadcaster.append_log(clean_text)

                updated_task = self.tracker.upsert_from_stream_line(clean_text)
                if updated_task is not None:
                    await self.broadcaster.publish(
                        {
                            "type": "task_update",
                            "task": updated_task,
                            "stats": self.tracker.stats,
                            "run_name": self.tracker.run_name,
                        }
                    )
                await self.broadcaster.publish({"type": "log", "line": clean_text})

        streams = [s for s in (proc.stdout, proc.stderr) if s is not None]
        if streams:
            await asyncio.gather(*(_read_stream(s) for s in streams))

        rc = await proc.wait()
        await asyncio.sleep(1.0)
        await asyncio.to_thread(self.reconcile_from_trace_file)

        self.tracker.return_code = rc
        if self.tracker.cancel_requested:
            self.tracker.status = "cancelled"
        else:
            self.tracker.status = "completed" if rc == 0 else "failed"

        if self.tracker.end_time is None:
            self.tracker.end_time = time.time()
        self.process = None
        self.tracker.compute_stats()

        exit_msg = f"\n[Process exited with code {rc}]\n"
        self.broadcaster.append_log(exit_msg)
        await self.broadcaster.publish({"type": "log", "line": exit_msg})
        await self.broadcaster.publish(
            {
                "type": "process_exit",
                "return_code": rc,
                "status": self.tracker.status,
                "stats": self.tracker.stats,
                "tasks": list(self.tracker.tasks.values()),
                "start_time": self.tracker.start_time,
                "end_time": self.tracker.end_time,
            }
        )

    def reconcile_from_trace_file(self) -> None:
        if not self._config_repo.exists() or self.tracker.start_time is None:
            return
        try:
            cfg, _ = self._config_repo.load()
            pipeline_info_dir = self._settings.results_base_dir / cfg.experiment / "pipeline_info"
            self.tracker.reconcile_from_trace_file(pipeline_info_dir)
        except Exception as exc:  # noqa: BLE001 - best-effort enrichment from optional Nextflow trace
            logger.warning("reconcile_from_trace_file skipped: %s", exc)

    async def handle_webhook(self, payload: dict[str, Any]) -> dict[str, str]:
        event = payload.get("event")
        run_name = payload.get("runName")
        if run_name and not self.tracker.run_name:
            self.tracker.run_name = str(run_name)

        trace = payload.get("trace")
        if isinstance(trace, dict) and trace:
            task_data = self.tracker.upsert_from_webhook_trace(trace)
            await self.broadcaster.publish(
                {
                    "type": "task_update",
                    "task": task_data,
                    "stats": self.tracker.stats,
                    "run_name": self.tracker.run_name,
                }
            )
            return {"status": "ok"}

        if event == "started":
            self.tracker.run_name = str(run_name) if run_name else None
            if self.tracker.start_time is None:
                self.tracker.start_time = time.time()
            self.tracker.compute_stats()
            await self.broadcaster.publish(
                {
                    "type": "run_started",
                    "run_name": self.tracker.run_name,
                    "stats": self.tracker.stats,
                    "start_time": self.tracker.start_time,
                }
            )
        elif event == "completed":
            wf = payload.get("metadata", {}).get("workflow", {})
            success = bool(wf.get("success", True))
            wf_stats = wf.get("stats", {})
            if self.tracker.end_time is None:
                self.tracker.end_time = time.time()

            self.tracker.ingest_completed_workflow_stats(wf_stats)
            await asyncio.to_thread(self.reconcile_from_trace_file)

            nf_cached = int(wf_stats.get("cachedCount", 0) or 0)
            nf_total = int(wf_stats.get("totalCount", len(self.tracker.tasks)) or 0)
            if nf_cached > self.tracker.reported_cached:
                self.tracker.reported_cached = nf_cached
            if nf_total > self.tracker.reported_total:
                self.tracker.reported_total = nf_total
            if not self.tracker.cancel_requested:
                self.tracker.status = "completed" if success else "failed"
            self.tracker.compute_stats()
            if success and self.tracker.stats["total"] > 0:
                self.tracker.stats["completed"] = self.tracker.stats["total"]
                self.tracker.stats["percent"] = 100.0

            await self.broadcaster.publish(
                {
                    "type": "run_completed",
                    "success": success,
                    "stats": self.tracker.stats,
                    "tasks": list(self.tracker.tasks.values()),
                    "start_time": self.tracker.start_time,
                    "end_time": self.tracker.end_time,
                }
            )

        return {"status": "ok"}

    def get_status(self) -> dict[str, Any]:
        self.tracker.compute_stats()
        return {
            "status": self.tracker.status,
            "pid": self.process.pid if self.process else None,
            "return_code": self.tracker.return_code,
            "log_lines_count": self.broadcaster.history_count,
            "run_name": self.tracker.run_name,
            "stats": self.tracker.stats,
            "tasks": list(self.tracker.tasks.values()),
            "start_time": self.tracker.start_time,
            "end_time": self.tracker.end_time,
        }
